"""Idiomas de la plataforma.

Cada idioma es un diccionario plano con las mismas claves. Añadir uno nuevo es
copiar `ES`, traducir los valores y registrarlo en `LANGUAGES`: un test
comprueba que ningún idioma se deje claves sin traducir.

Qué idioma se usa, por orden de prioridad:
  1. el que la persona eligió en su configuración
  2. el que eligió en la pantalla de acceso (cookie)
  3. el que pide el navegador (cabecera Accept-Language)
  4. el idioma por defecto del restaurante
  5. español
"""
from dataclasses import dataclass

DEFAULT_LANG = "es"
COOKIE_NAME = "grill_lang"


@dataclass(frozen=True)
class Language:
    code: str
    name: str        # nombre en su propio idioma
    direction: str   # ltr o rtl


LANGUAGES: dict[str, Language] = {
    "es": Language("es", "Español", "ltr"),
    "en": Language("en", "English", "ltr"),
    "fr": Language("fr", "Français", "ltr"),
    "de": Language("de", "Deutsch", "ltr"),
    "nl": Language("nl", "Nederlands", "ltr"),
    "ar": Language("ar", "العربية", "rtl"),
}


def is_supported(code: str | None) -> bool:
    return bool(code) and code in LANGUAGES


def direction(code: str) -> str:
    return LANGUAGES[code].direction if code in LANGUAGES else "ltr"


def from_accept_language(header: str | None) -> str | None:
    """Primer idioma aceptado por el navegador que sepamos hablar."""
    if not header:
        return None
    entries = []
    for part in header.split(","):
        bits = part.strip().split(";q=")
        tag = bits[0].strip().lower()
        try:
            q = float(bits[1]) if len(bits) > 1 else 1.0
        except ValueError:
            q = 0.0
        if tag:
            entries.append((q, tag))
    for _, tag in sorted(entries, key=lambda e: -e[0]):
        base = tag.split("-")[0]
        if is_supported(base):
            return base
    return None


def resolve(user_lang: str | None = None, cookie: str | None = None,
            accept_header: str | None = None, restaurant_lang: str | None = None) -> str:
    for candidate in (user_lang, cookie, from_accept_language(accept_header), restaurant_lang):
        if is_supported(candidate):
            return candidate
    return DEFAULT_LANG


def t(lang: str, key: str, **kw) -> str:
    """Texto traducido. Si falta la clave cae al español y, en último término,
    devuelve la propia clave: nunca revienta una pantalla por un texto."""
    table = TRANSLATIONS.get(lang) or TRANSLATIONS[DEFAULT_LANG]
    value = table.get(key)
    if value is None:
        value = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            return value.format(**kw)
        except (KeyError, IndexError):
            return value
    return value


def translator(lang: str):
    """Versión atada a un idioma, que es lo que reciben las plantillas."""
    def _t(key: str, **kw) -> str:
        return t(lang, key, **kw)
    return _t


